"""BibTeX generation, in code.

The original blueprint asked a model to maintain `library.bib`. A model can
invent a field or unbalance a brace; a function cannot. Cite keys are the paper
IDs, so `\\cite{P-0007}` in LaTeX matches the inline `[P-0007]` in the draft.
"""

from __future__ import annotations

import re

from .models import Paper

_SPECIALS = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "#": r"\#",
    "_": r"\_",
    "$": r"\$",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}

ENTRY_TYPES = {
    "peer_reviewed": "article",
    "grey": "techreport",
    "web": "misc",
    "unknown": "misc",
}


def escape(value: str) -> str:
    return "".join(_SPECIALS.get(ch, ch) for ch in value or "")


def _author_field(authors: list[str]) -> str:
    names = [a.strip() for a in authors if a and a.strip()]
    return " and ".join(escape(n) for n in names[:30])


def entry_for(paper: Paper) -> str:
    kind = ENTRY_TYPES.get(paper.source_type, "misc")
    fields: list[tuple[str, str]] = [("title", escape(paper.title.strip()))]
    authors = _author_field(paper.authors)
    if authors:
        fields.append(("author", authors))
    if paper.year:
        fields.append(("year", str(paper.year)))
    if paper.venue:
        key = "journal" if kind == "article" else "institution" if kind == "techreport" else "howpublished"
        fields.append((key, escape(paper.venue.strip())))
    if paper.doi:
        fields.append(("doi", escape(paper.doi.strip())))
    if paper.url:
        fields.append(("url", paper.url.strip()))
    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields)
    return f"@{kind}{{{paper.id},\n{body}\n}}"


def build(papers: list[Paper], header: str = "") -> str:
    """Full-pass build: one entry per paper, sorted by ID, header preserved."""
    ordered = sorted(papers, key=lambda p: p.id)
    head = header.strip() or (
        "% library.bib — generated by Bibliometric Studio\n"
        "% Cite keys are paper IDs (P-0001); they match the inline [P-0001] markers.\n"
        "% Regenerated from papers.json — edit the records, not this file."
    )
    entries = "\n\n".join(entry_for(p) for p in ordered)
    return f"{head}\n\n{entries}\n" if entries else f"{head}\n"


def validate(text: str) -> list[str]:
    """Structural checks: balanced braces, unique keys, required fields."""
    problems: list[str] = []
    depth = 0
    for i, ch in enumerate(text):
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth < 0:
                problems.append(f"unbalanced '}}' at char {i}")
                depth = 0
    if depth != 0:
        problems.append(f"{depth} unclosed brace(s)")
    keys = re.findall(r"@\w+\{([^,]+),", text)
    seen: set[str] = set()
    for key in keys:
        if key in seen:
            problems.append(f"duplicate cite key: {key}")
        seen.add(key)
    for block in re.split(r"\n(?=@)", text):
        if not block.startswith("@"):
            continue
        if "title" not in block:
            problems.append(f"entry without title: {block.splitlines()[0][:40]}")
    return problems
