"""Markdown agent files: parse, edit, compile.

An agent is one markdown file with YAML front-matter and `##` sections. The UI
turns each section into a field box; the engine compiles the body plus a locked
contract into the system prompt.

Why the split (APP_PLAN.md §8.3): the text is *behavior* the user may shape, the
contract is a *guarantee* the engine enforces. Editing "cite or omit" out of the
prompt must not be able to disable citation checking, so the citation contract is
appended here, in code.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

import yaml

AGENT_IDS = ("researcher", "author", "critic")

# ---------------------------------------------------------------------------
# locked contracts — appended to the system prompt, never editable in the UI
# ---------------------------------------------------------------------------

CONTRACTS: dict[str, str] = {
    "researcher": """
## Engine contract (not editable)

You are being asked to PLAN SEARCH QUERIES, not to answer questions and not to
write the deliverable. Respond with ONE JSON object and nothing else:

{"queries": [{"query": "<search string>", "theme": "<theme name>"}]}

Rules enforced by the engine:
- 3 to 8 queries, keyword-rich, suitable for OpenAlex/Crossref full-text search.
- Prefer English terms; include Portuguese/Spanish synonyms when the brief asks.
- Never invent a source, a DOI, or a fact.
""",
    "author": """
## Engine contract (not editable)

You write ONE SECTION of a document per call, using only the EVIDENCE provided.
The engine enforces these rules mechanically:

1. Every factual sentence must end with a citation of the form [P-0007] or
   [P-0007 p.3]. A sentence without a citation must be framing, not a claim.
2. You may cite only paper IDs present in the EVIDENCE block. Any other ID is
   reported as unresolved and fails the document.
3. Do not fabricate references, quotes, numbers, DOIs or author names. If the
   evidence does not support a point, omit the point or say the evidence is thin.
4. Do not write the References section; it is generated by the engine from the
   registered sources.
5. Represent genuinely distinct viewpoints. Attribute each position to a source ID
   instead of collapsing them into one narrative.
6. Output markdown for the section body only: no document title, no preamble,
   no code fences, no meta-commentary about these instructions.
""",
    "critic": """
## Engine contract (not editable)

Respond with ONE JSON object and nothing else:

{
  "findings": [
    {"severity": "blocker|major|minor|info",
     "target": "researcher|author|none",
     "location": "<section heading or quote>",
     "issue": "<what is wrong>",
     "suggestion": "<concrete fix>"}
  ],
  "summary": "<two sentences for the human owner>"
}

Rules enforced by the engine:
- Do not rewrite the document. You produce findings only.
- Use "researcher" as target when missing evidence is the problem, "author" when
  the argument or writing is the problem.
- Be specific: name the section and the paper ID you checked.
""",
}

CONTRACT_TITLES = {
    "researcher": "Query planning",
    "author": "Section drafting",
    "critic": "Structured review",
}


# ---------------------------------------------------------------------------
# parsing / rendering
# ---------------------------------------------------------------------------


@dataclass
class AgentSection:
    heading: str
    body: str = ""


@dataclass
class AgentFile:
    agent_id: str
    meta: dict[str, Any] = field(default_factory=dict)
    preamble: str = ""
    sections: list[AgentSection] = field(default_factory=list)
    parse_warnings: list[str] = field(default_factory=list)

    # -- parse --------------------------------------------------------------

    _FM = re.compile(r"\A---\s*\n(.*?)\n---\s*\n?", re.DOTALL)

    @classmethod
    def parse(cls, agent_id: str, text: str) -> "AgentFile":
        meta: dict[str, Any] = {}
        rest = text
        warnings: list[str] = []
        m = cls._FM.match(text)
        if m:
            try:
                loaded = yaml.safe_load(m.group(1)) or {}
                if isinstance(loaded, dict):
                    meta = loaded
                else:
                    warnings.append("front-matter is not a mapping; ignored")
            except yaml.YAMLError as exc:
                warnings.append(f"front-matter YAML error: {exc}")
            rest = text[m.end():]

        preamble_lines: list[str] = []
        sections: list[AgentSection] = []
        current: AgentSection | None = None
        for line in rest.splitlines():
            if line.startswith("## "):
                current = AgentSection(heading=line[3:].strip())
                sections.append(current)
            elif current is None:
                preamble_lines.append(line)
            else:
                current.body += line + "\n"

        for s in sections:
            s.body = s.body.strip("\n")
        return cls(
            agent_id=agent_id,
            meta=meta,
            preamble="\n".join(preamble_lines).strip("\n"),
            sections=sections,
            parse_warnings=warnings,
        )

    # -- render -------------------------------------------------------------

    def to_text(self) -> str:
        lines: list[str] = []
        if self.meta:
            lines.append("---")
            lines.append(yaml.safe_dump(self.meta, sort_keys=False, allow_unicode=True).strip())
            lines.append("---")
            lines.append("")
        if self.preamble.strip():
            lines.append(self.preamble.strip())
            lines.append("")
        for s in self.sections:
            lines.append(f"## {s.heading}")
            if s.body.strip():
                lines.append("")
                lines.append(s.body.strip())
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"

    def as_payload(self) -> dict[str, Any]:
        return {
            "agent_id": self.agent_id,
            "meta": self.meta,
            "preamble": self.preamble,
            "sections": [{"heading": s.heading, "body": s.body} for s in self.sections],
            "raw": self.to_text(),
            "parse_warnings": self.parse_warnings,
            "contract": CONTRACTS.get(self.agent_id, "").strip(),
            "contract_title": CONTRACT_TITLES.get(self.agent_id, ""),
        }

    @classmethod
    def from_payload(cls, agent_id: str, payload: dict[str, Any]) -> "AgentFile":
        sections = [
            AgentSection(heading=str(s.get("heading", "")).strip(), body=str(s.get("body", "")))
            for s in payload.get("sections", [])
            if str(s.get("heading", "")).strip()
        ]
        return cls(
            agent_id=agent_id,
            meta=dict(payload.get("meta") or {}),
            preamble=str(payload.get("preamble") or ""),
            sections=sections,
        )

    # -- behavior -----------------------------------------------------------

    def section(self, heading: str) -> str:
        low = heading.lower()
        for s in self.sections:
            if s.heading.lower() == low:
                return s.body
        return ""

    def body(self) -> str:
        """The user-editable instruction text (no front-matter, no contract)."""
        parts: list[str] = []
        if self.preamble.strip():
            parts.append(self.preamble.strip())
        for s in self.sections:
            parts.append(f"## {s.heading}\n\n{s.body.strip()}".rstrip())
        return "\n\n".join(parts).strip()

    def temperature(self, default: float = 0.2) -> float:
        try:
            return float(self.meta.get("temperature", default))
        except (TypeError, ValueError):
            return default

    def max_tokens(self, default: int = 2000) -> int:
        try:
            return int(self.meta.get("max_output_tokens", default))
        except (TypeError, ValueError):
            return default

    def system_prompt(self) -> str:
        """Body + locked contract. This is what the model actually receives."""
        return f"{self.body()}\n\n{CONTRACTS.get(self.agent_id, '')}".strip()

    def label(self) -> str:
        return str(self.meta.get("label") or self.agent_id.title())


def render_variables(text: str, variables: dict[str, Any]) -> str:
    """Substitute {{name}} placeholders; unknown names are left visible on purpose."""
    def sub(match: re.Match[str]) -> str:
        key = match.group(1).strip()
        val = variables.get(key)
        if val is None:
            return match.group(0)
        if isinstance(val, list):
            return "; ".join(str(v) for v in val)
        return str(val)

    return re.sub(r"\{\{\s*([A-Za-z0-9_.]+)\s*\}\}", sub, text)


def variables_from_brief(brief: Any) -> dict[str, Any]:
    return {
        "project.title": brief.title,
        "project.topic": brief.topic,
        "project.geography": brief.geography,
        "project.output_language": brief.output_language,
        "project.languages": brief.lit_languages,
        "project.disciplines": brief.disciplines,
        "workplan.rqs": [rq.question for rq in brief.rqs],
        "workplan.sections": brief.deliverable.sections,
        "workplan.length_words": brief.deliverable.length_words,
        "workplan.tone": brief.deliverable.tone,
        "min_sources": brief.min_sources,
        "viewpoints": [v.label for v in brief.viewpoints],
    }


def estimate_tokens(text: str) -> int:
    """Rough but stable: ~4 characters per token."""
    return max(1, len(text) // 4)
